'''
🐍⚔️ Q13/200 — Multiplication Pattern

Write a Python program that:

Uses a while loop
Starts with number = 1
Goes from 1 to 10
Prints the multiplication result of number × 7
Each result on a separate line
Do not use a for loop
Do not use break
Expected output:
7
14
21
28
35
42
49
56
63
70

🔥 New concept: Use the changing number inside a calculation.

Your turn, Python Warrior! 🐍⚔️
'''
number = 1
while number <= 10:
    result = number * 7
    print(result)
    number += 1