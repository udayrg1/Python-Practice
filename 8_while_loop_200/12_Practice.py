'''
🐍⚔️ Q12/200 — Step Counter

Write a Python program that:

Uses a while loop
Starts with number = 0
Goes up to 50
Prints numbers increasing by 5
Each number on a separate line
Do not use a for loop
Do not use break

Expected output:

0
5
10
15
20
25
30
35
40
45
50
'''

number = 0

while number <= 50:
    print(number)
    number += 5