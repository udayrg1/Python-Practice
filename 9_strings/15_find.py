'''
String Challenge 15 — .find()
Let's continue! 😎
product_code = "AMZ-84729-IN"



Find the starting index of "84729" using .find() and print it.
Expected output:
4
'''
product_code = "AMZ-84729-IN"

index = product_code.find("84729")


print(index)

# Remember:
# - len(product_code) gives the total number of characters.
# - len(product_code) - 1 gives the last character's index.
# - product_code.find("84729") gives the starting index of the substring you're searching for. 💪